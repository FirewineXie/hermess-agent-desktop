export function labels(language: Language) {
  const table = language === 'zh-CN' ? zh : en
  return (key: keyof typeof zh, ...args: Array<string | number>) =>
    table[key].replace(/\{(\d+)\}/g, (_, index: string) => String(args[Number(index)] ?? ''))
}
